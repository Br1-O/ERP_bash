-- Contrato de referencia para el endpoint de sincronización híbrida.
--
-- El cliente usa tres modos sobre la misma URL:
--   POST ...?mode=events  -> SELECT erp.apply_events($1::jsonb);
--   GET  ...?mode=pull&since_id=N -> SELECT erp.pull_events(N);
--   POST ...?mode=snapshot -> SELECT erp.sync_snapshot($1::jsonb);
--
-- El endpoint HTTP debe autenticar el token (Authorization: Bearer ... /
-- apikey: ...), leer el cuerpo JSON y devolver 2xx con el JSON de la función.
--
-- Este script es idempotente: se puede ejecutar varias veces. No borra filas
-- remotas que ya no existan en SQLite; el snapshot solo inserta/actualiza.

CREATE SCHEMA IF NOT EXISTS erp;

CREATE TABLE IF NOT EXISTS erp.categories (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS erp.suppliers (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    contact_person text,
    phone text,
    email text,
    address text,
    active smallint NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS erp.customers (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    type text NOT NULL DEFAULT 'Minorista',
    phone text,
    email text,
    active smallint NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS erp.inputs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    category_id integer REFERENCES erp.categories(id),
    stock numeric(14,2) NOT NULL DEFAULT 0,
    unit text NOT NULL DEFAULT 'unidades',
    cost numeric(14,2) NOT NULL DEFAULT 0,
    supplier_id integer REFERENCES erp.suppliers(id),
    min_stock_threshold numeric(14,2) NOT NULL DEFAULT 0,
    active smallint NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS erp.products (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE,
    category_id integer REFERENCES erp.categories(id),
    stock integer NOT NULL DEFAULT 0,
    min_production_threshold integer NOT NULL DEFAULT 0,
    cost numeric(14,2) NOT NULL DEFAULT 0,
    price numeric(14,2) NOT NULL DEFAULT 0,
    active smallint NOT NULL DEFAULT 1,
    is_seasonal smallint NOT NULL DEFAULT 0,
    recipe_description text NOT NULL DEFAULT '',
    is_combo smallint NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS erp.product_recipe (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id integer NOT NULL REFERENCES erp.products(id),
    input_id integer NOT NULL REFERENCES erp.inputs(id),
    quantity_per_unit numeric(14,4) NOT NULL
);

CREATE TABLE IF NOT EXISTS erp.product_recipe_steps (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id integer NOT NULL REFERENCES erp.products(id) ON DELETE CASCADE,
    step_number integer NOT NULL,
    instruction text NOT NULL,
    UNIQUE (product_id, step_number)
);

CREATE TABLE IF NOT EXISTS erp.combo_items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    combo_product_id integer NOT NULL REFERENCES erp.products(id) ON DELETE CASCADE,
    component_product_id integer NOT NULL REFERENCES erp.products(id),
    quantity integer NOT NULL CHECK (quantity > 0),
    UNIQUE (combo_product_id, component_product_id)
);

CREATE TABLE IF NOT EXISTS erp.business_info (
    id integer PRIMARY KEY,
    name text NOT NULL,
    instagram text NOT NULL DEFAULT '',
    facebook text NOT NULL DEFAULT '',
    phone text NOT NULL DEFAULT '',
    email text NOT NULL DEFAULT '',
    website text NOT NULL DEFAULT '',
    updated_at timestamp NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS erp.sales (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp timestamp NOT NULL,
    customer_id integer REFERENCES erp.customers(id),
    subtotal_amount numeric(14,2) NOT NULL DEFAULT 0,
    discount_type text NOT NULL DEFAULT 'none',
    discount_value numeric(14,2) NOT NULL DEFAULT 0,
    discount_amount numeric(14,2) NOT NULL DEFAULT 0,
    total_amount numeric(14,2) NOT NULL DEFAULT 0,
    payment_method text NOT NULL DEFAULT 'Efectivo',
    status text NOT NULL DEFAULT 'finished',
    notes text,
    created_by text NOT NULL DEFAULT 'sistema',
    stock_applied smallint NOT NULL DEFAULT 0,
    order_type text NOT NULL DEFAULT 'direct',
    order_stage text NOT NULL DEFAULT 'delivered',
    cancel_reason text,
    cancelled_by text,
    cancel_authorized_by text,
    cancelled_at timestamp,
    event_id integer,
    channel text NOT NULL DEFAULT 'LOCAL'
