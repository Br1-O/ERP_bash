CREATE TABLE IF NOT EXISTS erp.sale_items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id integer NOT NULL REFERENCES erp.sales(id) ON DELETE CASCADE,
    product_id integer NOT NULL REFERENCES erp.products(id),
    quantity integer NOT NULL,
    unit_price numeric(14,2) NOT NULL
);

CREATE TABLE IF NOT EXISTS erp.events (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    location text NOT NULL DEFAULT '',
    start_date date NOT NULL,
    end_date date,
    status text NOT NULL DEFAULT 'active',
    notes text NOT NULL DEFAULT '',
    created_by text NOT NULL DEFAULT 'sistema',
    closed_by text,
    total_revenue_cents bigint NOT NULL DEFAULT 0,
    total_cogs_cents bigint NOT NULL DEFAULT 0,
    total_loss_cents bigint NOT NULL DEFAULT 0,
    net_profit_cents bigint NOT NULL DEFAULT 0,
    created_at timestamp NOT NULL DEFAULT now(),
    closed_at timestamp
);

CREATE TABLE IF NOT EXISTS erp.event_stock (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id integer NOT NULL REFERENCES erp.events(id) ON DELETE CASCADE,
    product_id integer NOT NULL REFERENCES erp.products(id),
    allocated_qty integer NOT NULL DEFAULT 0,
    sold_qty integer NOT NULL DEFAULT 0,
    loss_qty integer NOT NULL DEFAULT 0,
    returned_qty integer NOT NULL DEFAULT 0,
    unit_cost_snapshot numeric(14,2) NOT NULL DEFAULT 0,
    created_at timestamp NOT NULL DEFAULT now(),
    updated_at timestamp NOT NULL DEFAULT now(),
    UNIQUE (event_id, product_id)
);

CREATE TABLE IF NOT EXISTS erp.event_ledger (
    event_uuid uuid PRIMARY KEY,
    action text NOT NULL,
    entity text,
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    received_at timestamp NOT NULL DEFAULT now()
