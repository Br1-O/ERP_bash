CREATE OR REPLACE FUNCTION erp.apply_events(payload jsonb)
RETURNS jsonb
LANGUAGE plpgsql
AS $function$
DECLARE
    remote_schema integer;
    event_row jsonb;
    event_uuid_value uuid;
    action_value text;
    entity_value text;
    body jsonb;
    delta numeric;
    product_id_value integer;
    sale_id_value integer;
    processed jsonb := '[]'::jsonb;
BEGIN
    IF payload->>'source' IS DISTINCT FROM 'sqlite' THEN
        RAISE EXCEPTION 'Lote no reconocido: source=sqlite esperado';
    END IF;

    remote_schema := COALESCE((payload->>'schema_version')::integer, 0);
    IF remote_schema <> 8 THEN
        RAISE EXCEPTION 'Versión de esquema no soportada: %', remote_schema;
    END IF;

    FOR event_row IN
        SELECT value FROM jsonb_array_elements(COALESCE(payload->'events', '[]'::jsonb))
    LOOP
        event_uuid_value := NULLIF(event_row->>'event_uuid', '')::uuid;
        CONTINUE WHEN event_uuid_value IS NULL;

        action_value := COALESCE(event_row->>'action', '');
        entity_value := COALESCE(event_row->>'entity', '');
        body := CASE
            WHEN jsonb_typeof(event_row->'payload') = 'object' THEN event_row->'payload'
            WHEN jsonb_typeof(event_row->'payload') = 'string' THEN (event_row->>'payload')::jsonb
            ELSE '{}'::jsonb
        END;

        INSERT INTO erp.event_ledger (event_uuid, action, entity, payload)
        VALUES (event_uuid_value, action_value, entity_value, body)
        ON CONFLICT (event_uuid) DO NOTHING;

        IF FOUND THEN
            product_id_value := NULLIF(body->>'product_id', '')::integer;
            delta := NULLIF(body->>'stock_delta', '')::numeric;

            IF action_value = 'SALE_STOCK_OUT' AND delta IS NULL THEN
                delta := -COALESCE(NULLIF(body->>'qty', '')::numeric, 0);
            END IF;

            IF product_id_value IS NOT NULL AND delta IS NOT NULL THEN
                UPDATE erp.products
                   SET stock = stock + delta
                 WHERE id = product_id_value;
            END IF;

            sale_id_value := NULLIF(body->>'sale_id', '')::integer;

            IF action_value = 'SALE_CREATED' AND sale_id_value IS NOT NULL THEN
                INSERT INTO erp.sales (
                    id, timestamp, customer_id, total_amount, payment_method,
                    status, order_type, order_stage, event_id, channel
                ) VALUES (
                    sale_id_value,
                    COALESCE(NULLIF(event_row->>'timestamp', '')::timestamp, now()),
                    NULLIF(body->>'customer_id', '')::integer,
                    COALESCE(NULLIF(body->>'total', '')::numeric, 0),
                    COALESCE(NULLIF(body->>'payment', ''), 'Efectivo'),
                    COALESCE(NULLIF(body->>'status', ''), 'finished'),
                    COALESCE(NULLIF(body->>'order_type', ''), 'direct'),
                    COALESCE(NULLIF(body->>'order_stage', ''), 'delivered'),
                    NULLIF(body->>'event_id', '')::integer,
                    COALESCE(NULLIF(body->>'channel', ''), 'LOCAL')
                )
                ON CONFLICT (id) DO UPDATE SET
                    total_amount = EXCLUDED.total_amount,
                    payment_method = EXCLUDED.payment_method,
                    status = EXCLUDED.status,
                    order_type = EXCLUDED.order_type,
                    order_stage = EXCLUDED.order_stage,
                    event_id = EXCLUDED.event_id,
                    channel = EXCLUDED.channel;
            END IF;

            IF action_value = 'SALE_TOTAL_UPDATED' AND sale_id_value IS NOT NULL THEN
                UPDATE erp.sales
                   SET total_amount = COALESCE(NULLIF(body->>'total', '')::numeric,
                                               total_amount)
                 WHERE id = sale_id_value;
            END IF;
        END IF;

        processed := processed || jsonb_build_array(event_uuid_value::text);
    END LOOP;

    RETURN jsonb_build_object(
        'ok', true,
        'schema_version', remote_schema,
        'event_uuids', processed,
        'processed', jsonb_array_length(processed)
    );
END;
$function$;

CREATE OR REPLACE FUNCTION erp.pull_events(since_id bigint DEFAULT 0)
RETURNS jsonb
LANGUAGE sql
AS $function$
    SELECT jsonb_build_object(
        'ok', true,
        'last_remote_journal_id',
        COALESCE((SELECT MAX(id) FROM erp.remote_events), since_id),
        'events',
        COALESCE((
            SELECT jsonb_agg(jsonb_build_object(
                'remote_id', id,
                'event_uuid', event_uuid,
                'action', action,
                'payload', payload
            ) ORDER BY id)
            FROM erp.remote_events
            WHERE id > since_id
        ), '[]'::jsonb)
    );
$function$;

CREATE OR REPLACE FUNCTION erp.enqueue_remote_event(
    action_value text,
    payload_value jsonb,
    event_uuid_value uuid DEFAULT gen_random_uuid()
)
RETURNS bigint
LANGUAGE plpgsql
AS $function$
DECLARE
    new_id bigint;
BEGIN
    INSERT INTO erp.remote_events (event_uuid, action, payload)
    VALUES (event_uuid_value, action_value, payload_value)
    ON CONFLICT (event_uuid) DO NOTHING
    RETURNING id INTO new_id;

    IF new_id IS NULL THEN
        SELECT id INTO new_id FROM erp.remote_events WHERE event_uuid = event_uuid_value;
    END IF;

    RETURN new_id;
END;
$function$;

