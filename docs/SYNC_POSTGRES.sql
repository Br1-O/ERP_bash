CREATE OR REPLACE FUNCTION erp.sync_snapshot(payload jsonb)
RETURNS jsonb
LANGUAGE plpgsql
AS $function$
DECLARE
    remote_schema integer;
BEGIN
    IF payload->>'source' IS DISTINCT FROM 'sqlite' THEN
        RAISE EXCEPTION 'Snapshot no reconocido: source=sqlite esperado';
    END IF;

    remote_schema := COALESCE((payload->>'schema_version')::integer, 0);
    IF remote_schema <> 8 THEN
        RAISE EXCEPTION 'Versión de esquema no soportada: %', remote_schema;
    END IF;

    INSERT INTO erp.categories (id, name)
    SELECT x.id, x.name
    FROM jsonb_to_recordset(COALESCE(payload->'tables'->'categories', '[]'::jsonb))
         AS x(id integer, name text)
    ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name;

    INSERT INTO erp.suppliers (id, name, contact_person, phone, email, address, active)
    SELECT x.id, x.name, x.contact_person, x.phone, x.email, x.address,
           COALESCE(x.active, 1)
    FROM jsonb_to_recordset(COALESCE(payload->'tables'->'suppliers', '[]'::jsonb))
         AS x(id integer, name text, contact_person text, phone text, email text,
              address text, active smallint)
    ON CONFLICT (id) DO UPDATE SET
        name = EXCLUDED.name, contact_person = EXCLUDED.contact_person,
        phone = EXCLUDED.phone, email = EXCLUDED.email, address = EXCLUDED.address,
        active = EXCLUDED.active;

    INSERT INTO erp.customers (id, name, type, phone, email, active)
    SELECT x.id, x.name, COALESCE(x.type, 'Minorista'), x.phone, x.email,
           COALESCE(x.active, 1)
    FROM jsonb_to_recordset(COALESCE(payload->'tables'->'customers', '[]'::jsonb))
         AS x(id integer, name text, type text, phone text, email text, active smallint)
    ON CONFLICT (id) DO UPDATE SET
        name = EXCLUDED.name, type = EXCLUDED.type,
        phone = EXCLUDED.phone, email = EXCLUDED.email, active = EXCLUDED.active;

    INSERT INTO erp.inputs (id, name, category_id, stock, unit, cost, supplier_id,
                            min_stock_threshold, active)
    SELECT x.id, x.name, x.category_id, x.stock, COALESCE(x.unit, 'unidades'),
           x.cost, x.supplier_id, x.min_stock_threshold, COALESCE(x.active, 1)
    FROM jsonb_to_recordset(COALESCE(payload->'tables'->'inputs', '[]'::jsonb))
         AS x(id integer, name text, category_id integer, stock numeric, unit text,
              cost numeric, supplier_id integer, min_stock_threshold numeric, active smallint)
    ON CONFLICT (id) DO UPDATE SET
        name = EXCLUDED.name, category_id = EXCLUDED.category_id,
        stock = EXCLUDED.stock, unit = EXCLUDED.unit, cost = EXCLUDED.cost,
        supplier_id = EXCLUDED.supplier_id,
        min_stock_threshold = EXCLUDED.min_stock_threshold, active = EXCLUDED.active;

    INSERT INTO erp.products (id, name, category_id, stock, min_production_threshold,
                              cost, price, active, is_seasonal, recipe_description, is_combo)
    SELECT x.id, x.name, x.category_id, x.stock, x.min_production_threshold,
           x.cost, x.price, COALESCE(x.active, 1), COALESCE(x.is_seasonal, 0),
           COALESCE(x.recipe_description, ''), COALESCE(x.is_combo, 0)
    FROM jsonb_to_recordset(COALESCE(payload->'tables'->'products', '[]'::jsonb))
         AS x(id integer, name text, category_id integer, stock integer,
              min_production_threshold integer, cost numeric, price numeric,
              active smallint, is_seasonal smallint, recipe_description text,
              is_combo smallint)
    ON CONFLICT (id) DO UPDATE SET
        name = EXCLUDED.name, category_id = EXCLUDED.category_id,
        stock = EXCLUDED.stock,
        min_production_threshold = EXCLUDED.min_production_threshold,
        cost = EXCLUDED.cost, price = EXCLUDED.price,
        active = EXCLUDED.active, is_seasonal = EXCLUDED.is_seasonal,
        recipe_description = EXCLUDED.recipe_description,
        is_combo = EXCLUDED.is_combo;

    INSERT INTO erp.product_recipe (id, product_id, input_id, quantity_per_unit)
    SELECT x.id, x.product_id, x.input_id, x.quantity_per_unit
    FROM jsonb_to_recordset(COALESCE(payload->'tables'->'product_recipe', '[]'::jsonb))
         AS x(id integer, product_id integer, input_id integer, quantity_per_unit numeric)
    ON CONFLICT (id) DO UPDATE SET
        product_id = EXCLUDED.product_id, input_id = EXCLUDED.input_id,
        quantity_per_unit = EXCLUDED.quantity_per_unit;

    INSERT INTO erp.product_recipe_steps (id, product_id, step_number, instruction)
    SELECT x.id, x.product_id, x.step_number, x.instruction
    FROM jsonb_to_recordset(COALESCE(payload->'tables'->'product_recipe_steps', '[]'::jsonb))
         AS x(id integer, product_id integer, step_number integer, instruction text)
    ON CONFLICT (id) DO UPDATE SET
        product_id = EXCLUDED.product_id, step_number = EXCLUDED.step_number,
        instruction = EXCLUDED.instruction;

    INSERT INTO erp.combo_items (id, combo_product_id, component_product_id, quantity)
    SELECT x.id, x.combo_product_id, x.component_product_id, x.quantity
    FROM jsonb_to_recordset(COALESCE(payload->'tables'->'combo_items', '[]'::jsonb))
         AS x(id integer, combo_product_id integer, component_product_id integer, quantity integer)
    ON CONFLICT (id) DO UPDATE SET
        combo_product_id = EXCLUDED.combo_product_id,
        component_product_id = EXCLUDED.component_product_id,
        quantity = EXCLUDED.quantity;

    INSERT INTO erp.business_info (id, name, instagram, facebook, phone, email, website, updated_at)
    SELECT x.id, x.name, COALESCE(x.instagram, ''), COALESCE(x.facebook, ''),
           COALESCE(x.phone, ''), COALESCE(x.email, ''), COALESCE(x.website, ''),
           COALESCE(x.updated_at, now())
    FROM jsonb_to_recordset(COALESCE(payload->'tables'->'business_info', '[]'::jsonb))
         AS x(id integer, name text, instagram text, facebook text, phone text,
              email text, website text, updated_at timestamp)
    ON CONFLICT (id) DO UPDATE SET
        name = EXCLUDED.name, instagram = EXCLUDED.instagram,
        facebook = EXCLUDED.facebook, phone = EXCLUDED.phone,
        email = EXCLUDED.email, website = EXCLUDED.website,
        updated_at = EXCLUDED.updated_at;

    INSERT INTO erp.sales (id, timestamp, customer_id, subtotal_amount, discount_type,
                           discount_value, discount_amount, total_amount, payment_method,
                           status, notes, created_by, stock_applied, order_type,
                           order_stage, cancel_reason, cancelled_by,
                           cancel_authorized_by, cancelled_at, event_id, channel)
    SELECT x.id, x.timestamp, x.customer_id, x.subtotal_amount,
           COALESCE(x.discount_type, 'none'), COALESCE(x.discount_value, 0),
           COALESCE(x.discount_amount, 0), x.total_amount,
           COALESCE(x.payment_method, 'Efectivo'), COALESCE(x.status, 'finished'),
           x.notes, COALESCE(x.created_by, 'sistema'), COALESCE(x.stock_applied, 0),
           COALESCE(x.order_type, 'direct'),
           CASE
               WHEN COALESCE(x.status, 'finished') = 'cancel' THEN 'cancel'
               WHEN COALESCE(x.order_type, 'direct') = 'direct' THEN 'delivered'
               WHEN COALESCE(x.status, 'finished') = 'finished' THEN 'delivered'
               ELSE COALESCE(x.order_stage, 'pending')
           END,
           x.cancel_reason, x.cancelled_by, x.cancel_authorized_by, x.cancelled_at,
           x.event_id, COALESCE(x.channel, 'LOCAL')
    FROM jsonb_to_recordset(COALESCE(payload->'tables'->'sales', '[]'::jsonb))
         AS x(id integer, timestamp timestamp, customer_id integer, subtotal_amount numeric,
              discount_type text, discount_value numeric, discount_amount numeric,
              total_amount numeric, payment_method text, status text, notes text,
              created_by text, stock_applied smallint, order_type text,
              order_stage text, cancel_reason text, cancelled_by text,
              cancel_authorized_by text, cancelled_at timestamp,
              event_id integer, channel text)
    ON CONFLICT (id) DO UPDATE SET
        timestamp = EXCLUDED.timestamp, customer_id = EXCLUDED.customer_id,
        subtotal_amount = EXCLUDED.subtotal_amount,
        discount_type = EXCLUDED.discount_type,
        discount_value = EXCLUDED.discount_value,
        discount_amount = EXCLUDED.discount_amount,
        total_amount = EXCLUDED.total_amount,
        payment_method = EXCLUDED.payment_method,
        status = EXCLUDED.status, notes = EXCLUDED.notes,
        created_by = EXCLUDED.created_by, stock_applied = EXCLUDED.stock_applied,
        order_type = EXCLUDED.order_type, order_stage = EXCLUDED.order_stage,
        cancel_reason = EXCLUDED.cancel_reason,
        cancelled_by = EXCLUDED.cancelled_by,
        cancel_authorized_by = EXCLUDED.cancel_authorized_by,
        cancelled_at = EXCLUDED.cancelled_at,
        event_id = EXCLUDED.event_id, channel = EXCLUDED.channel;

    INSERT INTO erp.sale_items (id, sale_id, product_id, quantity, unit_price)
    SELECT x.id, x.sale_id, x.product_id, x.quantity, x.unit_price
    FROM jsonb_to_recordset(COALESCE(payload->'tables'->'sale_items', '[]'::jsonb))
         AS x(id integer, sale_id integer, product_id integer, quantity integer, unit_price numeric)
    ON CONFLICT (id) DO UPDATE SET
        sale_id = EXCLUDED.sale_id, product_id = EXCLUDED.product_id,
        quantity = EXCLUDED.quantity, unit_price = EXCLUDED.unit_price;

    INSERT INTO erp.production_batches (id, timestamp, product_id, quantity, unit_cost, notes)
    SELECT x.id, x.timestamp, x.product_id, x.quantity, x.unit_cost, x.notes
    FROM jsonb_to_recordset(COALESCE(payload->'tables'->'production_batches', '[]'::jsonb))
         AS x(id integer, timestamp timestamp, product_id integer, quantity integer,
              unit_cost numeric, notes text)
    ON CONFLICT (id) DO UPDATE SET
        timestamp = EXCLUDED.timestamp, product_id = EXCLUDED.product_id,
        quantity = EXCLUDED.quantity, unit_cost = EXCLUDED.unit_cost, notes = EXCLUDED.notes;

    INSERT INTO erp.production_inputs (id, batch_id, input_id, quantity)
    SELECT x.id, x.batch_id, x.input_id, x.quantity
    FROM jsonb_to_recordset(COALESCE(payload->'tables'->'production_inputs', '[]'::jsonb))
         AS x(id integer, batch_id integer, input_id integer, quantity numeric)
    ON CONFLICT (id) DO UPDATE SET
        batch_id = EXCLUDED.batch_id, input_id = EXCLUDED.input_id,
        quantity = EXCLUDED.quantity;

    INSERT INTO erp.purchases (id, timestamp, supplier_id, total_amount, notes,
                               status, created_by, stock_applied)
    SELECT x.id, x.timestamp, x.supplier_id, x.total_amount, x.notes,
           COALESCE(x.status, 'pending'), x.created_by, COALESCE(x.stock_applied, 0)
    FROM jsonb_to_recordset(COALESCE(payload->'tables'->'purchases', '[]'::jsonb))
         AS x(id integer, timestamp timestamp, supplier_id integer, total_amount numeric,
              notes text, status text, created_by text, stock_applied smallint)
    ON CONFLICT (id) DO UPDATE SET
        timestamp = EXCLUDED.timestamp, supplier_id = EXCLUDED.supplier_id,
        total_amount = EXCLUDED.total_amount, notes = EXCLUDED.notes,
        status = EXCLUDED.status, created_by = EXCLUDED.created_by,
        stock_applied = EXCLUDED.stock_applied;

    INSERT INTO erp.purchase_items (id, purchase_id, input_id, quantity, unit_cost)
    SELECT x.id, x.purchase_id, x.input_id, x.quantity, x.unit_cost
    FROM jsonb_to_recordset(COALESCE(payload->'tables'->'purchase_items', '[]'::jsonb))
         AS x(id integer, purchase_id integer, input_id integer, quantity numeric, unit_cost numeric)
    ON CONFLICT (id) DO UPDATE SET
        purchase_id = EXCLUDED.purchase_id, input_id = EXCLUDED.input_id,
        quantity = EXCLUDED.quantity, unit_cost = EXCLUDED.unit_cost;

    INSERT INTO erp.tasting_feedback (id, product_id, accepted, timestamp)
    SELECT x.id, x.product_id, COALESCE(x.accepted, 0), x.timestamp
    FROM jsonb_to_recordset(COALESCE(payload->'tables'->'tasting_feedback', '[]'::jsonb))
         AS x(id integer, product_id integer, accepted smallint, timestamp timestamp)
    ON CONFLICT (id) DO UPDATE SET
        product_id = EXCLUDED.product_id, accepted = EXCLUDED.accepted,
        timestamp = EXCLUDED.timestamp;

    INSERT INTO erp.events (id, name, location, start_date, end_date, status,
                            notes, created_by, closed_by, total_revenue_cents,
                            total_cogs_cents, total_loss_cents, net_profit_cents,
                            created_at, closed_at)
    SELECT x.id, x.name, COALESCE(x.location, ''), x.start_date, x.end_date,
           COALESCE(x.status, 'active'), COALESCE(x.notes, ''),
           COALESCE(x.created_by, 'sistema'), x.closed_by,
           COALESCE(x.total_revenue_cents, 0), COALESCE(x.total_cogs_cents, 0),
           COALESCE(x.total_loss_cents, 0), COALESCE(x.net_profit_cents, 0),
           COALESCE(x.created_at, now()), x.closed_at
    FROM jsonb_to_recordset(COALESCE(payload->'tables'->'events', '[]'::jsonb))
         AS x(id integer, name text, location text, start_date date, end_date date,
              status text, notes text, created_by text, closed_by text,
              total_revenue_cents bigint, total_cogs_cents bigint,
              total_loss_cents bigint, net_profit_cents bigint,
              created_at timestamp, closed_at timestamp)
    ON CONFLICT (id) DO UPDATE SET
