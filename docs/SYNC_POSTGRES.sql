CREATE TABLE IF NOT EXISTS erp.remote_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_uuid uuid NOT NULL UNIQUE,
    action text NOT NULL,
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
